export function normalizeUrduForSearch(input: string): string {
  return input
    .replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '') // strip araab / diacritics
    .replace(/ك/g, 'ک')
    .replace(/ي/g, 'ی')
    .replace(/ى/g, 'ی')
    .replace(/ة/g, 'ہ')
    .replace(/أ|إ|آ/g, 'ا')
    .trim()
    .toLowerCase();
}

